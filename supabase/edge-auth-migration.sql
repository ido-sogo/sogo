CREATE TABLE IF NOT EXISTS public.auth_sessions (
    token_hash text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.auth_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_hash text NOT NULL,
    attempted_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS auth_sessions_expiry_idx
    ON public.auth_sessions (expires_at);
CREATE INDEX IF NOT EXISTS auth_attempts_ip_time_idx
    ON public.auth_attempts (ip_hash, attempted_at);
CREATE INDEX IF NOT EXISTS auth_attempts_time_idx
    ON public.auth_attempts (attempted_at);

ALTER TABLE public.auth_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auth_attempts ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.auth_sessions, public.auth_attempts
    FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.auth_sessions, public.auth_attempts
    TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.auth_attempts_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.consume_auth_attempt(
    p_ip_hash text,
    p_window_seconds integer,
    p_max_attempts integer
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    recent_count integer;
BEGIN
    IF p_ip_hash IS NULL OR p_window_seconds <= 0 OR p_max_attempts <= 0 THEN
        RAISE EXCEPTION 'Invalid rate limit parameters.'
            USING ERRCODE = '22023';
    END IF;

    PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_ip_hash, 0));
    DELETE FROM public.auth_attempts
    WHERE attempted_at < now() - interval '1 day';

    SELECT count(*)::integer
    INTO recent_count
    FROM public.auth_attempts
    WHERE ip_hash = p_ip_hash
      AND attempted_at >= now() - make_interval(secs => p_window_seconds);

    IF recent_count >= p_max_attempts THEN
        RETURN false;
    END IF;

    INSERT INTO public.auth_attempts (ip_hash) VALUES (p_ip_hash);
    RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.clear_auth_attempts(p_ip_hash text)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $function$
    DELETE FROM public.auth_attempts
    WHERE ip_hash = p_ip_hash;
$function$;

REVOKE ALL ON FUNCTION public.consume_auth_attempt(text, integer, integer)
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.clear_auth_attempts(text)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.consume_auth_attempt(text, integer, integer)
    TO service_role;
GRANT EXECUTE ON FUNCTION public.clear_auth_attempts(text)
    TO service_role;

CREATE OR REPLACE FUNCTION public.move_group_and_delete(
    p_source_name text,
    p_target_name text
)
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $function$
BEGIN
    IF p_source_name IS NULL
        OR p_target_name IS NULL
        OR p_source_name = p_target_name THEN
        RAISE EXCEPTION 'Choose a different destination group.'
            USING ERRCODE = '22023';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM public.groups WHERE name = p_source_name) THEN
        RAISE EXCEPTION 'Source group not found.'
            USING ERRCODE = 'P0002';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM public.groups WHERE name = p_target_name) THEN
        RAISE EXCEPTION 'Destination group not found.'
            USING ERRCODE = 'P0002';
    END IF;

    UPDATE public.users
    SET group_name = p_target_name
    WHERE group_name = p_source_name;

    UPDATE public.calendar_items
    SET group_name = p_target_name
    WHERE group_name = p_source_name;

    UPDATE public.outings
    SET group_name = p_target_name
    WHERE group_name = p_source_name;

    DELETE FROM public.groups
    WHERE name = p_source_name;
END;
$function$;

REVOKE ALL ON FUNCTION public.move_group_and_delete(text, text)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.move_group_and_delete(text, text)
    TO service_role;
